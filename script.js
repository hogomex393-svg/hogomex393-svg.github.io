function arrangeSite() {
  heroSection.after(journeySection);
  journeySection.after(manifestoSection);
  if (site === "recruiting") {
    manifestoSection.after(internshipSection);
    internshipSection.after(workSection);
    workSection.after(contactSection);
  } else {
    manifestoSection.after(workSection);
    workSection.after(internshipSection);
    internshipSection.after(contactSection);
  }
  updateHeaderTheme();
}
document.querySelector("[data-year]").textContent = new Date().getFullYear();

const header = document.querySelector("[data-header]");
const darkSections = [...document.querySelectorAll(".manifesto, .internship")];
let headerTicking = false;

function updateHeaderTheme() {
  const headerFocusY = header.getBoundingClientRect().bottom / 2;
  const isOverDarkSection = darkSections.some((section) => {
    const rect = section.getBoundingClientRect();
    return rect.top <= headerFocusY && rect.bottom >= headerFocusY;
  });
  header.classList.toggle("on-dark", isOverDarkSection);
  headerTicking = false;
}

window.addEventListener("scroll", () => {
  if (headerTicking) return;
  headerTicking = true;
  requestAnimationFrame(updateHeaderTheme);
}, { passive: true });
window.addEventListener("resize", updateHeaderTheme);
updateHeaderTheme();
arrangeSite();

const loader = document.querySelector("[data-loader]");
const loaderNumber = loader.querySelector("b");
const loadStart = performance.now();
function runLoader(now) {
  const progress = Math.min((now - loadStart) / 950, 1);
  loaderNumber.textContent = String(Math.round(progress * 100)).padStart(2, "0");
  if (progress < 1) requestAnimationFrame(runLoader);
  else window.setTimeout(() => loader.classList.add("loaded"), reducedMotion ? 0 : 180);
}
requestAnimationFrame(runLoader);

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    entry.target.classList.add("visible");
    revealObserver.unobserve(entry.target);
  });
}, { threshold: 0.12, rootMargin: "0px 0px -5% 0px" });
document.querySelectorAll(".reveal, .image-reveal").forEach((node) => revealObserver.observe(node));

const cursor = document.querySelector(".cursor");
let pointerX = window.innerWidth / 2;
let pointerY = window.innerHeight / 2;
let cursorX = pointerX;
let cursorY = pointerY;

window.addEventListener("pointermove", (event) => {
  pointerX = event.clientX;
  pointerY = event.clientY;
});

function moveCursor() {
  cursorX += (pointerX - cursorX) * .16;
  cursorY += (pointerY - cursorY) * .16;
  cursor.style.left = `${cursorX}px`;
  cursor.style.top = `${cursorY}px`;
  requestAnimationFrame(moveCursor);
}
if (!reducedMotion) requestAnimationFrame(moveCursor);

document.querySelectorAll("[data-project] a").forEach((project) => {
  project.addEventListener("mouseenter", () => cursor.classList.add("project-hover"));
  project.addEventListener("mouseleave", () => cursor.classList.remove("project-hover"));
});

const hero = document.querySelector(".hero");
const heroArt = document.querySelector("[data-parallax]");
hero.addEventListener("pointermove", (event) => {
  if (reducedMotion || window.innerWidth < 800) return;
  const x = (event.clientX / window.innerWidth - .5) * 18;
  const y = (event.clientY / window.innerHeight - .5) * 12;
  heroArt.style.transform = `translate3d(${x}px, ${y}px, 0)`;
});
hero.addEventListener("pointerleave", () => { heroArt.style.transform = ""; });

const mediaNodes = [...document.querySelectorAll(".project-media > img, .project-media > video")];
let scrollTicking = false;
function updateMediaParallax() {
  mediaNodes.forEach((node) => {
    const rect = node.parentElement.getBoundingClientRect();
    if (rect.bottom < 0 || rect.top > window.innerHeight) return;
    const center = rect.top + rect.height / 2 - window.innerHeight / 2;
    node.style.translate = `0 ${center * -.025}px`;
  });
  scrollTicking = false;
}
window.addEventListener("scroll", () => {
  if (reducedMotion || scrollTicking) return;
  scrollTicking = true;
  requestAnimationFrame(updateMediaParallax);
}, { passive: true });
